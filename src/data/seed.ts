// Helper to construct dynamic dates relative to current date (Oct 2026 / current runtime)
const now = new Date();
const addHours = (h: number) => new Date(now.getTime() + h * 3600 * 1000).toISOString();
const subHours = (h: number) => new Date(now.getTime() - h * 3600 * 1000).toISOString();
const addDays = (d: number, hours = 10) => {
  const target = new Date(now.getTime() + d * 24 * 3600 * 1000);
  target.setHours(hours, 0, 0, 0);
  return target.toISOString();
};

